#!/usr/bin/env node
// Snapshots the xStocks registry (Backed Finance) into web/lib/stock-tokens.generated.ts: every tokenised
// stock/ETF with a Solana mint. Re-run when Backed lists new assets.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const API = "https://api.backed.fi/api/v2/public/assets";
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "web", "lib", "stock-tokens.generated.ts");

const list = [];
for (let page = 1; page <= 20; page++) {
  const res = await fetch(`${API}?page=${page}`, { headers: { accept: "application/json" } });
  if (!res.ok) throw new Error(`backed assets ${res.status}`);
  const body = await res.json();
  for (const a of body.nodes ?? []) {
    const sol = a.deployments?.find((d) => d.network === "Solana");
    if (!sol || !a.underlyingSymbol) continue;
    list.push({
      mint: sol.address,
      symbol: a.underlyingSymbol,
      xSymbol: a.symbol,
      name: a.name.replace(/\s*xStock$/i, ""),
      isin: a.isin,
      logoUrl: a.logo ?? null,
    });
  }
  if ((body.nodes ?? []).length < 100) break;
}
const dedup = [...new Map(list.map((x) => [x.mint, x])).values()].sort((a, b) => a.symbol.localeCompare(b.symbol));

const src = `// generated by scripts/gen-stock-tokens.mjs from ${API} on ${new Date().toISOString().slice(0, 10)} — do not edit
export interface StockToken {
  mint: string;
  /** underlying ticker, e.g. NVDA */
  symbol: string;
  /** on-chain symbol, e.g. NVDAx */
  xSymbol: string;
  name: string;
  isin: string;
  logoUrl: string | null;
}

/** Every xStock with a Solana mint. Which of them a creator may put in a basket is decided on chain (AllowedBasketMint). */
export const MAINNET_STOCK_TOKENS: readonly StockToken[] = ${JSON.stringify(dedup, null, 2)};

export const STOCK_BY_SYMBOL: ReadonlyMap<string, StockToken> = new Map(MAINNET_STOCK_TOKENS.map((t) => [t.symbol, t]));
export const STOCK_BY_MINT: ReadonlyMap<string, StockToken> = new Map(MAINNET_STOCK_TOKENS.map((t) => [t.mint, t]));
`;
writeFileSync(out, src);
console.log(`wrote ${dedup.length} xStocks → ${out}`);
