#!/usr/bin/env node
/**
 * Downloads a logo for every tokenized stock into web/public/stocks/<SYMBOL>.png.
 *
 * The brokerage CDN returns the same generic house logo for every token (verified: 30/30
 * byte-identical), so the artwork has to come from elsewhere. Fetching at build time rather than
 * hotlinking keeps the UI independent of a third party's uptime and rate limits.
 *
 *   node scripts/gen-stock-logos.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "web/public/stocks");
const SRC = path.join(root, "web/lib/stock-tokens.generated.ts");
const { PNG } = createRequire(path.join(root, "web/package.json"))("pngjs");

/**
 * True when the artwork is essentially white — a logo drawn for dark backgrounds. A quarter of
 * these are, and on our paper-coloured circle they render as a blank disc, so they need an
 * inverted ground instead.
 */
function needsDarkGround(file) {
  try {
    const png = PNG.sync.read(fs.readFileSync(file));
    let opaque = 0;
    let luminance = 0;
    for (let i = 0; i < png.data.length; i += 4) {
      if (png.data[i + 3] < 40) continue; // transparent enough to ignore
      opaque++;
      luminance += (png.data[i] + png.data[i + 1] + png.data[i + 2]) / 3;
    }
    return opaque > 0 && luminance / opaque > 225;
  } catch {
    return false;
  }
}

// Tried in order; the first image wins.
const SOURCES = [
  (s) => `https://financialmodelingprep.com/image-stock/${s}.png`,
  (s) => `https://assets.parqet.com/logos/symbol/${s}?format=png`,
  (s) => `https://raw.githubusercontent.com/nvstly/icons/main/ticker_icons/${s}.png`,
];

const symbols = [...fs.readFileSync(SRC, "utf8").matchAll(/symbol: "([^"]+)"/g)].map((m) => m[1]);
if (symbols.length === 0) throw new Error(`no symbols found in ${SRC}`);
fs.mkdirSync(OUT, { recursive: true });

let written = 0;
const missing = [];
for (const symbol of symbols) {
  const file = path.join(OUT, `${symbol}.png`);
  if (fs.existsSync(file)) { written++; continue; }
  let saved = false;
  for (const url of SOURCES) {
    try {
      const res = await fetch(url(symbol), { signal: AbortSignal.timeout(15000) });
      if (!res.ok || !(res.headers.get("content-type") ?? "").startsWith("image")) continue;
      const buf = Buffer.from(await res.arrayBuffer());
      if (buf.byteLength < 200) continue; // a 1x1 or an error page dressed as an image
      fs.writeFileSync(file, buf);
      saved = true;
      break;
    } catch { /* try the next source */ }
  }
  saved ? written++ : missing.push(symbol);
  process.stdout.write(`\r${written + missing.length}/${symbols.length}`);
}
// A manifest so the UI can tell "we have artwork" from "render a monogram" without a network probe.
const have = fs.readdirSync(OUT).filter((f) => f.endsWith(".png")).map((f) => f.replace(/\.png$/, "")).sort();
const light = have.filter((sym) => needsDarkGround(path.join(OUT, `${sym}.png`)));
fs.writeFileSync(
  path.join(root, "web/lib/stock-logos.generated.ts"),
  `// Generated by scripts/gen-stock-logos.mjs — do not edit.\n` +
    `// Tickers with artwork in web/public/stocks. The brokerage CDN returns one generic house logo\n` +
    `// for every token, so these are fetched from public logo sources at build time instead.\n` +
    `export const STOCK_LOGOS: ReadonlySet<string> = new Set(${JSON.stringify(have)});\n\n` +
    `// White artwork meant for dark backgrounds; render these on an inverted ground.\n` +
    `export const STOCK_LOGOS_LIGHT: ReadonlySet<string> = new Set(${JSON.stringify(light)});\n`,
);
const bytes = fs.readdirSync(OUT).reduce((n, f) => n + fs.statSync(path.join(OUT, f)).size, 0);
console.log(`\n${written}/${symbols.length} logos in web/public/stocks (${(bytes / 1024 / 1024).toFixed(1)} MB)`);
console.log(`${light.length} need a dark ground (white artwork)`);
if (missing.length) console.log(`no artwork for: ${missing.join(", ")}`);
